-- ========================================================================
-- 数据库迁移脚本：添加镜像架构默认值支持
-- ========================================================================
-- 版本：v1.2.0
-- 创建时间：2024年
-- 目的：为镜像同步记录添加默认架构值，提高数据完整性
-- 
-- 背景说明：
-- Docker镜像支持多种CPU架构（如amd64、arm64、arm/v7等）
-- 在早期版本中，架构字段可能为空，导致同步时无法正确识别目标架构
-- 此迁移将为所有空架构字段设置默认值，并修改表结构确保新记录有默认值
-- 
-- 架构说明：
-- - amd64: 64位x86架构，最常用的服务器和桌面架构
-- - arm64: 64位ARM架构，用于ARM服务器和Apple M系列芯片
-- - arm/v7: 32位ARM架构，用于嵌入式设备和树莓派等
-- 
-- 执行前提：
-- - 确保数据库连接正常
-- - 建议在维护窗口期间执行
-- - 执行前请备份数据库
-- ========================================================================

-- ========================================================================
-- 1. 数据修复 - 为现有空架构记录设置默认值
-- ========================================================================
-- 功能：将所有空的或NULL的架构字段设置为amd64（最常用的架构）
-- 影响：所有architecture字段为NULL或空字符串的记录
UPDATE image_sync_records 
SET architecture = 'amd64' 
WHERE architecture IS NULL OR architecture = '';

-- ========================================================================
-- 2. 表结构优化 - 设置架构字段的默认值
-- ========================================================================
-- 功能：修改表结构，确保新插入的记录自动获得默认架构值
-- 影响：image_sync_records表的architecture字段
ALTER TABLE image_sync_records 
MODIFY COLUMN architecture VARCHAR(50) DEFAULT 'amd64' 
COMMENT '镜像架构（amd64/arm64/arm等，默认amd64）';

